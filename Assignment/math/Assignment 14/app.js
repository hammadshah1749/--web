let value = 10;
document.write("The value is "+value);

document.write("<br /><br />The value after ++a is "+ ++value);
document.write("<br />Now the value is "+ value);


document.write("<br /><br />The value after a++ is "+ value++);
document.write("<br />Now the value is "+ value);

document.write("<br /><br />The value after --a is "+ --value);
document.write("<br />Now the value is "+ value);

document.write("<br /><br />The value after a-- is "+ value--);
document.write("<br />Now the value is "+ value);
